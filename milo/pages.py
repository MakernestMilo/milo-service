def _vars(level):
    m = level.meta
    return f'--level:{m["colour"]};--on-level:{m["on_colour"]};--tint:{m.get("tint", "#F3EFE6")}'


def layout(title, body, level=None, chapter=None, description=""):
    style = f' style="{_vars(level)}"' if level else ""
    data = f' data-level="{E(level.id)}" data-chapter="{E(chapter)}"' if level and chapter else ""
    script = '<script src="/static/milo.js" defer></script>' if chapter else ""
    return f"""<!doctype html>
<html lang="en"{style}>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{E(title)}</title>
<meta name="description" content="{E(description)}">
<meta name="theme-color" content="{E(level.meta['colour']) if level else '#191713'}">
<link rel="stylesheet" href="/static/milo.css">
{script}
</head>
<body{data}>
{body}
</body>
</html>"""


def topbar(level=None, crumb=None):
    right = f'<a class="crumb" href="/{E(level.id)}">{E(crumb)}</a>' if level and crumb else ""
    return f'<div class="wrap top"><a class="brand" href="/{E(level.id) if level else "origins"}">{CAIRN}<span>makernest</span></a>{right}</div>'


