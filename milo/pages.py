# ------------------------------------------------------------------------------ a chapter
def _sketch_section(level, ch):
    key = ch.key
    sk = level.sketch(key)
    coach = key in level.meta.get("code_coach", [])
    if not sk:
        return ""
    fname = f"/{level.id}/{key}/sketch/{ch.sketch_key}.ino"
    if coach:
        intro = ("This is your starting point: every part on your machine is already named, and one example rule is there to change. "
                 "Copy it into File, New Sketch. Then we write the rest together, one line at a time, in Ask Milo below.")
        label, title = "starter sketch", "Your starter sketch"
    elif ch.sketch_key != key:
        intro = (f"Nothing new to upload this chapter: sketch {ch.sketch_key.upper()} stays on your board. "
                 "If you need to upload it again, here it is.")
        label, title = "sketch", f"Sketch {ch.sketch_key.upper()}, still on your board"
    elif key in ("01", "02"):
        page = {"01": 11, "02": 22}[key]
        intro = (f"This one is printed on page {page} of your book. Type it in yourself: copying it letter by letter is part of the chapter. "
                 "If it won't upload, compare yours with this one, line by line.")
        label, title = "sketch", f"Sketch {ch.label} {ch.title}"
    else:
        intro = ("Copy it, open File, New Sketch, select everything in the new window and paste over it. "
                 "Check Tools, Board says Arduino Uno and Tools, Port shows your board, then press Upload.")
        label, title = "sketch", f"Sketch {ch.label} {ch.title}"
    return f"""<section class="part" id="sketch"><h2>{E(title)}</h2><p class="lede">{E(intro)}</p>
{code_box("sk-" + key, sk, fname, label)}
<p class="note">Your settings and your notebook stay saved on the board when you upload.</p></section>"""


def _wiring_section(level, ch):
    figs = []
    for b in ch.wiring_new:
        if b in level.wiring:
            figs.append(f'<div class="figure"><p class="cap">New this chapter</p>{level.wiring[b]}</div>')
    lede = ("Red is power, black is the way back, and every signal has its own colour. On the shield, black goes to G, red to V, the signal to S. Every time."
            if figs else "Nothing new to wire in this chapter. Here is the whole shield, so you can check every wire.")
    whole = f'<div class="figure"><p class="cap">The whole shield, by the end of the book</p>{level.wiring.get("map", "")}</div>'
    return f'<section class="part" id="wiring"><h2>Wiring</h2><p class="lede">{E(lede)}</p>{"".join(figs)}{whole}</section>'


def _bench_one(level, key, b):
    names = level.bench.get("parts", {})
    parts = "".join(f"<li>{E(names.get(p, p))}</li>" for p in dict.fromkeys(b.get("parts", [])))
    counts = {}
    for p in b.get("parts", []):
        counts[p] = counts.get(p, 0) + 1
    parts = "".join(f"<li>{E(names.get(p, p))}{' × ' + str(n) if n > 1 else ''}</li>" for p, n in counts.items())
    svg = level.bench_svg.get(b.get("same_circuit_as") or key) or level.bench_svg.get(key, "")
    fig = f'<div class="figure"><p class="cap">On the breadboard</p>{svg}</div>' if svg else ""
    steps = "".join(f"<li>{E(s)}</li>" for s in b.get("steps", []))
    facts = "".join(f'<div class="fact"><b>{E(t)}</b><p>{E(b[k])}</p></div>'
                    for k, t in (("notice", "What you'll see"), ("break_it", "Break it on purpose"), ("try_this", "Then try"))
                    if b.get(k))
    safety = f'<p class="rules"><b>Safely:</b> {E(b["safety"])}</p>' if b.get("safety") else ""
    sk = ""
    if b.get("sketch") and b["sketch"] in level.bench_sketches:
        sk = code_box(f"bs-{key}", level.bench_sketches[b["sketch"]], f"/{level.id}/{key}/bench/{b['sketch']}.ino", "bench sketch")
    return f"""<p class="lede">{E(b.get("idea", ""))}</p>
{('<h3>You need</h3><ul class="parts-list">' + parts + '</ul>') if parts else ''}
{fig}
{('<h3>Build it</h3><ol class="steps">' + steps + '</ol>') if steps else ''}
{sk}
<div class="facts">{facts}</div>{safety}"""


def _faults(level, b):
    out = []
    for f in b["faults"]:
        svg = level.bench_svg.get(f"f{f['n']}", "")
        hints = "".join(f'<details><summary>Hint {i}</summary><p>{E(h)}</p></details>' for i, h in enumerate(f["hints"], 1))
        sk = ""
        if f.get("sketch") and f["sketch"] in level.bench_sketches:
            sk = code_box(f"fs-{f['n']}", level.bench_sketches[f["sketch"]], f"/{level.id}/11/bench/{f['sketch']}.ino", "sketch")
        out.append(f"""<details><summary>Fault {f["n"]} · {E(f["label"])}</summary>
<p><b>Build it like this:</b> {E(f["build"])}</p>
{('<div class="figure"><p class="cap">As built, wrong on purpose</p>' + svg + '</div>') if svg else ''}
{sk}
<p><b>It should:</b> {E(f["should"])}<br><b>It does:</b> {E(f["does"])}</p>
{hints}
<details><summary>The answer. Only when you have really tried.</summary><p>{E(f["answer"])}</p></details>
</details>""")
    return "".join(out)


def _bench_section(level, ch):
    b = ch.bench
    if not b:
        return ""
    rules = "".join(f"<p>{E(r)}</p>" for r in level.bench.get("rules", []))
    if b.get("faults"):
        inner = f'<p class="lede">{E(b["idea"])}</p>{_faults(level, b)}'
    elif b.get("ideas"):
        ideas = "".join(f'<li><a href="/{E(level.id)}/{E(k)}#bench">Bench {E(k.upper())}</a>: {E(t)}</li>' for k, t in b["ideas"])
        steps = "".join(f"<li>{E(s)}</li>" for s in b.get("steps", []))
        inner = f'<p class="lede">{E(b["idea"])}</p><ol class="steps">{steps}</ol><h3>Ideas for one change</h3><ul>{ideas}</ul>'
    else:
        inner = _bench_one(level, ch.key, b)
    return f"""<section class="part" id="bench"><h2>On the bench: {E(b["title"])}</h2>{inner}
<details><summary>How the bench works</summary><div class="rules">{rules}</div></details></section>"""


def chapter_page(level, ch):
    flag = ch.verb == "Flagship"
    eyebrow = f"{level.name} · {'Flagship' if flag else 'Chapter ' + ch.label + ' · ' + ch.verb}"
    chips = [("Time", ch.time), ("Needs", ch.needs), ("Open", ch.open)]
    chips_html = "".join(f"<li><b>{E(k.upper())}</b>{E(v)}</li>" for k, v in chips if v and v != "None")
    opts = "".join(f'<option value="{E(p)}">{E(p)}</option>' for p in ch.positions)
    has_sketch = bool(level.sketch(ch.key))
    nav = (('<a href="#sketch">Sketch</a>' if has_sketch else "") + '<a href="#wiring">Wiring</a>'
           + ('<a href="#bench">Bench</a>' if ch.bench else "") + '<a class="milo-link" href="#milo">Ask Milo</a>')
    i = level.order.index(ch.key)
    prev_k = level.order[i - 1] if i > 0 else None
    next_k = level.order[i + 1] if i + 1 < len(level.order) else None
    pn = "".join([f'<a class="btn" href="/{E(level.id)}/{E(prev_k)}">← {E(level.chapters[prev_k].title)}</a>' if prev_k else "",
                  f'<a class="btn" href="/{E(level.id)}/{E(next_k)}">{E(level.chapters[next_k].title)} →</a>' if next_k else ""])
    hello = {"11": "Somebody broke your machine, and I don't know how either. Start with the five places, in order. What have you tested so far?",
             "12": "This is the chapter where you write the code. Tell me your sentence: what should your machine do, and when?",
             "g": "Whose problem is it, and what did they say, in their own words? Start there and we'll build it together."}.get(
        ch.key, f"Hello. I'm here for {ch.title}. Pick your step at the top of the page, then tell me what you see.")
    body = f"""{topbar(level, f"{level.name} · all chapters")}
<header class="band"><div class="wrap">
<p class="eyebrow">{E(eyebrow)}</p>
<h1>{E(ch.title)}</h1>
<p class="aim">{E(ch.aim)}</p>
<ul class="chips">{chips_html}</ul>
<div class="where"><label for="where">Where are you?</label>
<select id="where"><option value="">Pick your step</option>{opts}</select></div>
</div></header>
<nav class="jump" aria-label="On this page"><div class="wrap">{nav}</div></nav>
<main class="wrap">
{_sketch_section(level, ch)}
{_wiring_section(level, ch)}
{_bench_section(level, ch)}
{milo_panel(level, ch.key, hello)}
<p class="codebar">{pn}</p>
</main>
{footer(level)}"""
    return layout(f"{ch.title} · MakerNest {level.name}", body, level, ch.key, ch.aim)


