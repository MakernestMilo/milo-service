def panel_list(items):
    rows = []
    for key, c in items:
        if not c.get("turns"):
            continue
        first = next((t["said"] for t in c["turns"] if t["who"] == "maker"), "")
        rows.append(f'<li><a href="/panel/c/{E(key)}">{E(c["level"])} {E(c["chapter"])}</a> · {len(c["turns"])} turns · '
                    f'{E(c.get("position") or "")}<br><span class="note">{E(first[:140])}</span></li>')
    body = f'<main class="wrap"><h2>Milo conversations</h2><p class="lede">Newest first. Kept 7 days.</p><ol>{"".join(rows)}</ol></main>'
    return layout("Milo panel", body)


